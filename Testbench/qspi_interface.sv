//=============================================================================
// Interface: qspi_if
// Purpose:   Virtual interface connecting the testbench to the QSPI DUT.
//            Bundles APB3 control/data signals, physical QSPI flash pins,
//            DMA handshaking lines, and interrupt signals.
//
// CORRECTED: 2026-09-07
//   - Added pstrb signal (was missing — DUT has pstrb[3:0] port)
//   - Added pstrb to DRV and MON modports
//   - Fixed clocking block timing for DRV (clocking cb_drv)
//   - Removed duplicate modport signal declarations
//=============================================================================
interface qspi_if();

  // =========================================================================
  // APB3 Bus Signals
  // =========================================================================
  logic        pclk;                     // APB clock (generated by top)
  logic        presetn = 1'b1;           // active-LOW reset

  logic        psel    = 1'b0;           // slave select
  logic        penable = 1'b0;           // access phase enable
  logic        pwrite  = 1'b0;           // direction: 1=write, 0=read
  logic [31:0] paddr   = 32'h0;          // address bus

  logic [31:0] pwdata  = 32'h0;          // write data bus
  wire  [31:0] prdata;                   // read data bus (DUT-driven)

  logic [3:0]  pstrb   = 4'hF;           // byte strobes (FIXED: was missing)

  wire         pready;                   // slave ready (DUT-driven)
  wire         pslverr;                  // slave error (DUT-driven)

  // =========================================================================
  // QSPI Physical Pins & Sideband Signals
  // =========================================================================
  wire         CS_n;                     // Chip Select (Active Low)
  wire         CLK;                      // Serial Clock output to Flash
  wire         FLASH_RST_n;              // Flash memory reset signal

  // Quad-SPI bidirectional data lines
  wire         D3;
  wire         D2;
  wire         D1;
  wire         D0;

  // Interrupts & DMA Handshake
  wire         irq;                      // Interrupt Request
  wire         rx_dma_req;               // RX DMA Request
  wire         tx_dma_req;               // TX DMA Request
  logic        rx_dma_ack = 1'b0;        // RX DMA Acknowledge (Driven by TB)
  logic        tx_dma_ack = 1'b0;        // TX DMA Acknowledge (Driven by TB)

  // =========================================================================
  // Test Control Hooks (for Protocol/Fault Verification)
  // =========================================================================
  logic TEST_VIO_EDGE       = 1'b0;      // when 1, suppresses stability assertion
  logic TEST_BACK_TO_BACK   = 1'b0;      // when 1, PSEL stays HIGH between transfers

  // =========================================================================
  // Clocking Block for Driver (cycle-accurate NBA drive)
  // =========================================================================
  clocking cb_drv @(posedge pclk);
    output presetn, psel, penable, pwrite, paddr, pwdata, pstrb;
    output rx_dma_ack, tx_dma_ack;
    output TEST_VIO_EDGE, TEST_BACK_TO_BACK;
    input  pready, pslverr, prdata;
    input  irq, rx_dma_req, tx_dma_req;
    input  CS_n, CLK, FLASH_RST_n;
    input  D3, D2, D1, D0;
  endclocking

  // =========================================================================
  // Modports
  // =========================================================================

  // Driver modport — drives master-side APB inputs & DMA acks, samples responses
  modport DRV(
    clocking cb_drv,                    // FIXED: use clocking block for NBA
    output presetn,
    output psel,
    output pwrite,
    output penable,
    output paddr,
    output pwdata,
    output pstrb,                        // FIXED: added pstrb
    output rx_dma_ack,
    output tx_dma_ack,
    output TEST_VIO_EDGE,
    output TEST_BACK_TO_BACK,
    input  pready,
    input  pslverr,
    input  prdata,
    input  pclk,
    input  irq,
    input  rx_dma_req,
    input  tx_dma_req,
    input  CS_n,
    input  CLK,
    input  FLASH_RST_n,
    input  D3,
    input  D2,
    input  D1,
    input  D0
  );

  // Monitor modport — passive observation of all APB and QSPI signals
  modport MON(
    input pclk,
    input presetn,
    input psel,
    input penable,
    input pwrite,
    input paddr,
    input pwdata,
    input prdata,
    input pstrb,                         // FIXED: added pstrb
    input pready,
    input pslverr,
    input CS_n,
    input CLK,
    input FLASH_RST_n,
    input D3,
    input D2,
    input D1,
    input D0,
    input irq,
    input rx_dma_req,
    input tx_dma_req,
    input rx_dma_ack,
    input tx_dma_ack,
    input TEST_VIO_EDGE,
    input TEST_BACK_TO_BACK
  );

  // =========================================================================
  // Interface-level Concurrent Assertions (SVA) - APB Protocol Integrity
  // =========================================================================

  // Signal integrity: no X/Z on control signals
  a_if_no_x_psel:      assert property(@(posedge pclk) disable iff (!presetn) !$isunknown(psel))
                        else $error("QSPI_IF: psel is X/Z");
  a_if_no_x_penable:   assert property(@(posedge pclk) disable iff (!presetn) !$isunknown(penable))
                        else $error("QSPI_IF: penable is X/Z");
  a_if_no_x_pwrite:    assert property(@(posedge pclk) disable iff (!presetn) !$isunknown(pwrite))
                        else $error("QSPI_IF: pwrite is X/Z");
  a_if_no_x_pready:    assert property(@(posedge pclk) disable iff (!presetn) !$isunknown(pready))
                        else $error("QSPI_IF: pready is X/Z");
  a_if_no_x_paddr:     assert property(
      @(posedge pclk) disable iff (!presetn)
      psel |-> !$isunknown(paddr) )
      else $error("QSPI_IF: paddr is X/Z when psel asserted");
  a_if_no_x_prdata:    assert property(
      @(posedge pclk) disable iff (!presetn)
      (psel && penable && pready) |-> !$isunknown(prdata) )
      else $error("QSPI_IF: prdata is X/Z during valid read");
  a_if_no_x_pslverr:   assert property(
      @(posedge pclk) disable iff (!presetn)
      (psel && penable && pready) |-> !$isunknown(pslverr) )
      else $error("QSPI_IF: pslverr is X/Z during valid handshake");

  // APB protocol assertions
  a_if_penable_implies_psel: assert property(
      @(posedge pclk) disable iff (!presetn)
      penable |-> psel )
      else $error("QSPI_IF: penable asserted without psel");

  a_if_setup_min_one_cycle: assert property(
      @(posedge pclk) disable iff (!presetn)
      $rose(penable) |-> $past(psel) && !$past(penable) )
      else $error("QSPI_IF: penable rose without prior SETUP cycle");

  a_if_stable_on_penable_rise: assert property(
      @(posedge pclk) disable iff (!presetn)
      ($rose(penable) && !TEST_VIO_EDGE) |-> $stable(paddr) && $stable(pwrite) && $stable(psel) )
      else $error("QSPI_IF: paddr/pwrite/psel changed on penable rise");

  // Back-to-back transfers
  a_if_btob_psel_stable: assert property(
      @(posedge pclk) disable iff (!presetn)
      (TEST_BACK_TO_BACK && $fell(penable)) |=> psel )
      else $error("QSPI_IF: psel de-asserted during back-to-back transfer");

  a_if_no_penable_without_psel: assert property(
      @(posedge pclk) disable iff (!presetn)
      !psel |-> !penable )
      else $error("QSPI_IF: penable asserted while psel is de-asserted");

  a_if_psel_stable_during_access: assert property(
      @(posedge pclk) disable iff (!presetn)
      (penable && !pready) |=> psel )
      else $error("QSPI_IF: psel dropped while waiting for pready");

  // Signal stability during ACCESS phase
  a_if_paddr_stable_in_access: assert property(
      @(posedge pclk) disable iff (!presetn)
      (penable && !pready) |-> $stable(paddr) )
      else $error("QSPI_IF: paddr changed while waiting for pready");

  a_if_pwrite_stable_in_access: assert property(
      @(posedge pclk) disable iff (!presetn)
      (penable && !pready) |-> $stable(pwrite) )
      else $error("QSPI_IF: pwrite changed while waiting for pready");

  a_if_pwdata_stable_in_write: assert property(
      @(posedge pclk) disable iff (!presetn)
      (penable && pwrite && !pready) |-> $stable(pwdata) )
      else $error("QSPI_IF: pwdata changed while waiting for pready");

  a_if_pslverr_valid_only: assert property(
      @(posedge pclk) disable iff (!presetn)
      pslverr |-> (psel && penable && pready) )
      else $error("QSPI_IF: pslverr asserted outside valid handshake window");

  a_if_penable_falls_after_pready: assert property(
      @(posedge pclk) disable iff (!presetn)
      !$past(pready) && pready && $past(penable) |=> !penable )
      else $error("QSPI_IF: penable did not fall after pready");

  // =========================================================================
  // Cover Properties
  // =========================================================================
  c_if_write_transfer:  cover property(@(posedge pclk) psel && penable && pwrite);
  c_if_read_transfer:   cover property(@(posedge pclk) psel && penable && !pwrite);
  c_if_wait_state:      cover property(@(posedge pclk) penable && !pready);
  c_if_error_response:  cover property(@(posedge pclk) psel && penable && pready && pslverr);
  c_if_back_to_back:    cover property(@(posedge pclk) $fell(penable) && $stable(psel));
  c_if_reset_active:    cover property(@(negedge pclk) !presetn);

  // QSPI-Specific Coverage
  c_if_qspi_active:     cover property(@(posedge pclk) !CS_n);

endinterface: qspi_if

